def set_run(run, cn='宋体', en='Times New Roman', size=BODY_SIZE, bold=False):
    run.font.name = en
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = BLACK
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), cn)
    rFonts.set(qn('w:ascii'), en)
    rFonts.set(qn('w:hAnsi'), en)


def add_h(text, level):
    p = doc.add_paragraph(style='Heading %d' % level)
    r = p.add_run(text)
    size = {1: 16, 2: 14, 3: 12}[level]
    before = {1: 14, 2: 11, 3: 9}[level]
    after = {1: 6, 2: 5, 3: 4}[level]
    set_run(r, cn='黑体', size=size, bold=True)
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.first_line_indent = Pt(0)
    pf.left_indent = Pt(0)
    pf.line_spacing = 1.5
    pf.keep_with_next = True
    return p


def add_body(text, indent=True):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_run(r)
    pf = p.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.line_spacing = 1.5
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.first_line_indent = Pt(24) if indent else Pt(0)
    return p


def add_lead(label, text):
    """小节内的条目：加粗小标题 + 正文，同段。"""
    p = doc.add_paragraph()
    r1 = p.add_run(label + ' ')
    set_run(r1, bold=True)
    r2 = p.add_run(text)
    set_run(r2)
    pf = p.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.line_spacing = 1.5
    pf.space_before = Pt(6)
    pf.space_after = Pt(0)
    pf.first_line_indent = Pt(0)
    return p


def add_caption(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_run(r, size=TABLE_SIZE)
    pf = p.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.line_spacing = 1.0
    pf.space_before = Pt(6)
    pf.space_after = Pt(4)
    pf.first_line_indent = Pt(0)
    pf.keep_with_next = True
    return p


def shade(cell, color='F2F2F2'):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color)
    tcPr.append(shd)


def add_table(caption, header, rows, widths):
    add_caption(caption)
    table = doc.add_table(rows=1, cols=len(header))
    table.style = 'Table Grid'
    table.autofit = False

    hdr = table.rows[0]
    trPr = hdr._tr.get_or_add_trPr()
    trPr.append(OxmlElement('w:tblHeader'))
    trPr.append(OxmlElement('w:cantSplit'))
    for i, text in enumerate(header):
        cell = hdr.cells[i]
        cell.width = Cm(widths[i])
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Pt(0)
        r = p.add_run(str(text))
        set_run(r, size=TABLE_SIZE, bold=True)
        shade(cell)

    for row_data in rows:
        row = table.add_row()
        row._tr.get_or_add_trPr().append(OxmlElement('w:cantSplit'))
        for i, text in enumerate(row_data):
            cell = row.cells[i]
            cell.width = Cm(widths[i])
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = cell.paragraphs[0]
            p.paragraph_format.first_line_indent = Pt(0)
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.0
            value = str(text)
            is_num = value.replace(',', '').replace('%', '').replace('-', '').replace('+', '').replace('¥', '').replace('.', '').replace(' ', '').isdigit()
            if i == 0:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            elif is_num:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            elif len(value) <= 6:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            else:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            r = p.add_run(value)
            set_run(r, size=TABLE_SIZE)
    return table


def add_page_number():
    footer = doc.sections[0].footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    set_run(run, size=10.5)
    begin = OxmlElement('w:fldChar')
    begin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = 'PAGE'
    end = OxmlElement('w:fldChar')
    end.set(qn('w:fldCharType'), 'end')
    run._r.append(begin)
    run._r.append(instr)
    run._r.append(end)


def add_toc():
    """插入可刷新的 Word 动态目录域，并设置打开时更新域。"""
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.first_line_indent = Pt(0)
    run = p.add_run()
    set_run(run)
    begin = OxmlElement('w:fldChar')
    begin.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-2" \\h \\z \\u'
    sep = OxmlElement('w:fldChar')
    sep.set(qn('w:fldCharType'), 'separate')
    end = OxmlElement('w:fldChar')
    end.set(qn('w:fldCharType'), 'end')
    placeholder = OxmlElement('w:t')
    placeholder.text = '（在 Word 中右键此处，选择“更新域”生成目录）'
    run._r.append(begin)
    run._r.append(instr)
    run._r.append(sep)
    run._r.append(placeholder)
    run._r.append(end)


